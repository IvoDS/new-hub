import fs from 'fs';
import path from 'path';
import { env } from './env.js';

export function ensureInitialUploads() {
  if (!fs.existsSync(env.UPLOAD_DIR)) {
    fs.mkdirSync(env.UPLOAD_DIR, { recursive: true });
  }

  const defaultCvPath = path.join(env.UPLOAD_DIR, 'ivan-de-stefani-cv.pdf');
  if (!fs.existsSync(defaultCvPath)) {
    console.log(`📄 Generating default placeholder CV at ${defaultCvPath}`);
    generatePlaceholderPdf(defaultCvPath);
  }
}

function generatePlaceholderPdf(outputPath: string) {
  const content = [
    'BT',
    '/F1 24 Tf',
    '50 720 Td',
    '(Ivan De Stefani - Curriculum Vitae) Tj',
    '/F1 14 Tf',
    '0 -30 Td',
    '(Cloud Architect, DevOps & Firmware Engineer) Tj',
    '0 -25 Td',
    '(Email: contact@ivandestefani.it | Website: https://ivandestefani.it) Tj',
    '0 -40 Td',
    '/F1 16 Tf',
    '(Key Competencies:) Tj',
    '/F1 12 Tf',
    '0 -25 Td',
    '(- Cloud Architecture & DevOps: Caddy, Docker, Blue/Green Deployments, CI/CD) Tj',
    '0 -20 Td',
    '(- High-Throughput APIs: Node.js, Fastify, MariaDB, Sequelize, JWT Auth) Tj',
    '0 -20 Td',
    '(- Frontend Architecture: React 19, Next.js 15, Tailwind CSS, TanStack Query) Tj',
    '0 -20 Td',
    '(- Embedded Systems & Firmware: C/C++, FreeRTOS, Zephyr, STM32, ESP32, CAN bus) Tj',
    '0 -50 Td',
    '/F1 10 Tf',
    '([Official CV placeholder generated by Hub. Update anytime via the Admin Panel.]) Tj',
    'ET',
  ].join('\n');

  const streamLength = Buffer.byteLength(content, 'utf8');

  let body = '%PDF-1.4\n';
  const offsets: number[] = [];

  function addObj(str: string) {
    offsets.push(Buffer.byteLength(body, 'utf8'));
    body += str + '\n';
  }

  addObj('1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj');
  addObj('2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj');
  addObj('3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>\nendobj');
  addObj('4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj');
  addObj('5 0 obj\n<< /Length ' + streamLength + ' >>\nstream\n' + content + '\nendstream\nendobj');

  const xrefOffset = Buffer.byteLength(body, 'utf8');
  body += 'xref\n0 6\n0000000000 65535 f \n';
  for (let i = 0; i < offsets.length; i++) {
    body += String(offsets[i]).padStart(10, '0') + ' 00000 n \n';
  }
  body += 'trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n' + xrefOffset + '\n%%EOF\n';

  fs.writeFileSync(outputPath, body, 'utf8');
}
